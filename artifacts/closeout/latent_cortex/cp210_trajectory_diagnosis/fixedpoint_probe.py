"""Is depth-8 saturation drift, semantics, or FIXED-POINT CONVERGENCE?

The recurrent operator applies the same W every step under RMSMatch +
alpha-interpolation. That combination is a contraction: it is *designed*
to converge. If the slot state reaches a fixed point by step ~8, then
additional steps perform no new computation BY CONSTRUCTION, and the
measured saturation is neither drift nor a semantic ceiling -- it is the
operator switching itself off.

Distinguishing signature:
  residual ||z_t - z_{t-1}|| / ||z_t||
    -> 0            => fixed point: steps stop computing (design defect)
    -> constant     => still computing; saturation is semantic
    -> growing      => drift/instability

If it is a fixed point, phase-indexed weights (a different operator per
step, generated by a cheap learned rotation) restore per-step novelty
without adding parameters.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path("/Users/bryan/.aura/live-source")
sys.path.insert(0, str(REPO))

import mlx.core as mx  # noqa: E402
from mlx_lm import load  # noqa: E402

from core.brain.llm.latent_cortex.execution_spec import RLCExecutionSpec  # noqa: E402
from core.learning import recurrence_curriculum as curriculum  # noqa: E402
import core.learning.recurrence_native_objective_v2 as objective  # noqa: E402

MODEL = str(REPO / "models/Qwen2.5-1.5B-Instruct-4bit")
MAX_DEPTH = 24


def main() -> int:
    print(f"loading {MODEL}\n", flush=True)
    model, tokenizer = load(MODEL)
    task = curriculum.task_battery(["khop"], [8], 1, seed=4242)[0]
    prompt = list(
        tokenizer.apply_chat_template(
            [{"role": "user", "content": task.prompt}],
            add_generation_prompt=True,
            tokenize=True,
        )
    )
    answer = list(tokenizer.encode(task.answer, add_special_tokens=False))

    # Capture the slot state after every recurrent step by instrumenting
    # the window pass the objective actually uses.
    captured: list = []
    original = objective._window_pass

    def recording_window_pass(*args, **kwargs):
        result = original(*args, **kwargs)
        captured.append(result)
        return result

    objective._window_pass = recording_window_pass
    try:
        spec = RLCExecutionSpec(
            n_slots=4,
            branch_roles=("constructive_solution",),
            recurrent_steps=MAX_DEPTH,
            exchange_interval=1,
        )
        objective.live_path_forward(
            model, prompt, answer, spec=spec.with_depth(MAX_DEPTH)
        )
    finally:
        objective._window_pass = original

    print(f"captured {len(captured)} recurrent states\n")
    if len(captured) < 3:
        print("instrumentation did not capture per-step states; aborting")
        return 1

    print("=== per-step change (is the operator still computing?) ===")
    print(f"{'step':>5s} {'residual':>10s} {'norm':>10s}")
    residuals = []
    norms = []
    for index in range(1, len(captured)):
        previous, current = captured[index - 1], captured[index]
        delta = mx.linalg.norm(mx.reshape(current - previous, (-1,)))
        scale = mx.maximum(mx.linalg.norm(mx.reshape(current, (-1,))), 1e-9)
        residual = float(delta / scale)
        norm = float(scale)
        mx.eval(delta, scale)
        residuals.append(residual)
        norms.append(norm)
        if index <= 16 or index % 4 == 0:
            print(f"{index:5d} {residual:10.6f} {norm:10.3f}")

    early = sum(residuals[:3]) / max(1, len(residuals[:3]))
    late = sum(residuals[-3:]) / max(1, len(residuals[-3:]))
    ratio = late / max(early, 1e-9)
    norm_ratio = norms[-1] / max(norms[0], 1e-9)
    print(f"\nearly residual (steps 1-3)  : {early:.6f}")
    print(f"late residual  (last 3)     : {late:.6f}")
    print(f"late/early ratio            : {ratio:.4f}")
    print(f"norm growth (last/first)    : {norm_ratio:.4f}")

    if ratio < 0.35:
        verdict = (
            "FIXED POINT — the operator converges and stops computing. "
            "Extra depth is structurally inert; phase-indexed weights would "
            "restore per-step novelty."
        )
    elif ratio > 2.0 or norm_ratio > 3.0 or norm_ratio < 0.33:
        verdict = "DRIFT — state is destabilizing; a norm-preserving operator would help."
    else:
        verdict = "STEADY — still computing each step; saturation is semantic."
    print(f"\nVERDICT: {verdict}")

    out = Path(__file__).with_name("fixedpoint_probe_result.json")
    out.write_text(
        json.dumps(
            {
                "model": MODEL,
                "max_depth": MAX_DEPTH,
                "residuals": [round(v, 8) for v in residuals],
                "norms": [round(v, 4) for v in norms],
                "early_residual": early,
                "late_residual": late,
                "late_over_early": ratio,
                "norm_growth": norm_ratio,
                "verdict": verdict,
            },
            indent=2,
        )
    )
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
